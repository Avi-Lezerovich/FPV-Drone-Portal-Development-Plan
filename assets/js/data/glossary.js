/** Glossary terms. */

export const GLOSSARY_DATA = [
  ['AIO', 'All-in-one board: flight controller and 4-in-1 ESC on one PCB, as in the Cinelog30 V3 TAKER F722 45A.'],
  ['AUW', 'All-up weight: the full takeoff weight including battery, GoPro, straps and LEDs. This is what counts for the 250 g limit.'],
  ['Airmode', 'Betaflight feature that keeps PID control active at zero throttle so the quad stays controllable during flips and dives.'],
  ['BEC', 'Battery eliminator circuit: a regulator on the FC that makes 5 V or 9/10 V from the battery. The O4 Pro uses 9 V or VBAT, never 5 V.'],
  ['Bi-directional DShot', 'ESC sends motor RPM back to the FC, which enables the RPM filter.'],
  ['Blackbox', 'On-board flight data logger used to analyse noise and tune PIDs.'],
  ['BNF / PNP', 'Bind-and-fly (receiver installed, just bind) / plug-and-play (no receiver, sometimes no VTX).'],
  ['Canvas mode (HD OSD)', 'Goggles setting that shows the full 53×20 Betaflight HD OSD grid without cropping the edges.'],
  ['CRSF', 'Crossfire serial protocol, which ExpressLRS uses between receiver and FC. Select it as the Serial RX provider.'],
  ['D-Log M', 'DJI 10-bit flat colour profile for grading footage. It needs colour correction afterwards.'],
  ['Diff all', 'Betaflight CLI command that prints every setting changed from defaults. Save it before changing anything.'],
  ['DShot', 'Digital ESC protocol (DShot300/600). Must match the PID loop speed.'],
  ['ELRS (ExpressLRS)', 'Open-source, low-latency, long-range RC link. Both quads use the 2.4 GHz version.'],
  ['Failsafe', 'What the quad does when the radio link is lost: drop (stage 2 off) or GPS Rescue.'],
  ['GPS Rescue', 'Betaflight return-to-home: climbs to a set altitude and flies back using GPS. This is not a precision landing.'],
  ['Gyroflow', 'Desktop software that stabilises footage using gyro data recorded by the O4 Pro.'],
  ['KV', 'Motor RPM per volt with no load. Lower KV suits higher voltage (1860 KV on 6S).'],
  ['LiHV', 'High-voltage lithium polymer cells charged to 4.35 V per cell. Select the LiHV mode on the charger.'],
  ['LQ', 'ELRS link quality as a percentage of packets received. It is a better health indicator than RSSI.'],
  ['LED_STRIP', 'Betaflight feature that drives WS2812B addressable LEDs from the FC LED pad.'],
  ['MSP DisplayPort', 'Protocol the FC uses to send the Betaflight OSD to the O4 Pro over a UART.'],
  ['ND filter', 'Neutral density filter that cuts light so the camera can use a slower shutter for cinematic motion blur.'],
  ['OSD', 'On-screen display: voltage, timer, link quality and warnings drawn over the video feed.'],
  ['PID', 'The control loop (proportional, integral, derivative) that keeps the quad where your sticks point.'],
  ['Props out', 'Prop rotation where the front props spin outward at the front of the quad. This throws debris away from the camera.'],
  ['RPM filter', 'Notch filters that follow motor RPM (from bi-directional DShot) to remove motor noise.'],
  ['RockSteady', 'DJI in-camera electronic stabilisation. It crops the frame. Turn it off if you use Gyroflow.'],
  ['Smoke stopper', 'Inline fuse or current limiter for the first power-up of a new build. It saves the ESC if there is a short.'],
  ['Turtle mode', 'Flip over after crash: spins motors in reverse to flip an upside-down quad.'],
  ['UART', 'Serial port on the FC. TX on one device always goes to RX on the other.'],
  ['VBAT', 'The raw battery voltage pad on the FC or ESC.'],
  ['VLOS', 'Visual line of sight: someone must be able to see the aircraft directly. With FPV goggles that is your spotter.'],
  ['WS2812B', 'Common 5 V addressable RGB LED chip used on FPV LED strips.']
].map(([term, def]) => ({ term, def }));
